def plen(p): return sum(math.dist(p[i],p[i+1]) for i in range(len(p)-1))
out={}
for h in range(1,19):
    pts=LINE[h]+[GC[h]]
    want=CARD[h][2]*.9144
    a=pts[1] if len(pts)>1 else GC[h]
    rest=plen(pts[1:]) if len(pts)>2 else 0
    t0=pts[0];ux,uy=t0[0]-a[0],t0[1]-a[1];l=math.hypot(ux,uy);ux/=l;uy/=l
    d=want-rest
    tee=(a[0]+ux*d,a[1]+uy*d) if h not in (14,) else t0   # the 14th: the tee where the club's plan puts it
    line=[tee]+pts[1:]
    out[h]={'tee':[round(tee[0],1),round(tee[1],1)],'line':[[round(x,1),round(y,1)] for x,y in line],'shift':round(d-l,1),'card':round(want,1)}
    print(h,'tee',out[h]['tee'],'moved',out[h]['shift'],'m vs rough tee')
json.dump({'card':CARD,'holes':out,'gc':GC},open('holes.json','w'))
